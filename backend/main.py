import os
import shutil
import tempfile
from functools import lru_cache
from pathlib import Path
from urllib.request import urlopen

import joblib
import pandas as pd
from fastapi import Depends, FastAPI, HTTPException
from fastapi.middleware.cors import CORSMiddleware
from pydantic import BaseModel, Field

app = FastAPI(
    title="Sales Prediction API",
    description="Predict weekly store sales using the trained Random Forest pipeline",
    version="1.1.0",
)

# Local Vite origins are enabled by default. Add the deployed frontend URL through
# FRONTEND_ORIGINS (comma-separated) instead of allowing every website.
default_origins = [
    "http://localhost:5173",
    "http://127.0.0.1:5173",
]
configured_origins = os.getenv("FRONTEND_ORIGINS", "")
allowed_origins = default_origins + [
    origin.strip().rstrip("/")
    for origin in configured_origins.split(",")
    if origin.strip()
]

app.add_middleware(
    CORSMiddleware,
    allow_origins=list(dict.fromkeys(allowed_origins)),
    allow_credentials=False,
    allow_methods=["GET", "POST"],
    allow_headers=["Content-Type"],
)

MODEL_PATH = Path(
    os.getenv(
        "MODEL_PATH",
        str(Path(__file__).resolve().parent / "models" / "random_forest_model.pkl"),
    )
)


def _download_model_if_configured() -> None:
    """Download a trusted model artifact when it is not present on disk.

    MODEL_ARTIFACT_URL must point directly to the .pkl file. Only use artifacts
    generated by this project; joblib files can execute code when loaded.
    """
    artifact_url = os.getenv("MODEL_ARTIFACT_URL")
    if MODEL_PATH.exists() or not artifact_url:
        return

    MODEL_PATH.parent.mkdir(parents=True, exist_ok=True)
    temporary_path = None

    try:
        with tempfile.NamedTemporaryFile(
            dir=MODEL_PATH.parent, suffix=".tmp", delete=False
        ) as temporary_file:
            temporary_path = Path(temporary_file.name)
            with urlopen(artifact_url, timeout=60) as response:
                shutil.copyfileobj(response, temporary_file)

        # Validate the downloaded artifact before making it the active model.
        downloaded_data = joblib.load(temporary_path)
        if not isinstance(downloaded_data, dict) or "model" not in downloaded_data:
            raise ValueError("Downloaded model artifact has an invalid format.")

        os.replace(temporary_path, MODEL_PATH)
    finally:
        if temporary_path and temporary_path.exists():
            temporary_path.unlink()


@lru_cache(maxsize=1)
def load_model_bundle():
    """Load the trained pipeline once; return None when no artifact is available."""
    _download_model_if_configured()

    if not MODEL_PATH.exists():
        return None

    saved_data = joblib.load(MODEL_PATH)
    if not isinstance(saved_data, dict) or "model" not in saved_data:
        raise ValueError("The saved model artifact has an invalid format.")

    return {
        "model": saved_data["model"],
        "metrics": saved_data.get("metrics", {}),
    }


def get_model_bundle():
    """FastAPI dependency used by endpoints that require a trained model."""
    bundle = load_model_bundle()
    if bundle is None:
        raise HTTPException(
            status_code=503,
            detail=(
                "Model artifact not found. Train it with "
                "'python run_pipeline.py' or configure MODEL_ARTIFACT_URL."
            ),
        )
    return bundle


class SalesInput(BaseModel):
    Store: int = Field(ge=1)
    Dept: int = Field(ge=1)
    IsHoliday: bool = False
    Temperature: float
    Fuel_Price: float
    MarkDown1: float = 0
    MarkDown2: float = 0
    MarkDown3: float = 0
    MarkDown4: float = 0
    MarkDown5: float = 0
    CPI: float
    Unemployment: float
    Type: str = Field(pattern="^[ABC]$")
    Size: int = Field(gt=0)
    Year: int = Field(ge=2010, le=2035)
    Month: int = Field(ge=1, le=12)
    Week: int = Field(ge=1, le=53)


@app.get("/")
def home():
    return {"message": "Sales Prediction API is running"}


@app.get("/health")
def health():
    """Health endpoint stays available even before a model is deployed."""
    bundle = load_model_bundle()
    return {"status": "healthy", "model_loaded": bundle is not None}


@app.get("/model-metrics")
def get_model_metrics():
    """Return evaluation metrics from the latest saved model training run."""
    bundle = load_model_bundle()
    if bundle is None or not bundle["metrics"]:
        return {
            "model": "Random Forest Regressor",
            "r2_score": None,
            "mae": None,
            "rmse": None,
            "message": (
                "Metrics unavailable. Train and deploy the model artifact first."
            ),
        }

    return bundle["metrics"]


@app.post("/predict")
def predict_sales(data: SalesInput, bundle=Depends(get_model_bundle)):
    input_df = pd.DataFrame([data.model_dump()])
    prediction = float(bundle["model"].predict(input_df)[0])

    return {
        "predicted_weekly_sales": round(prediction, 2),
        "store": data.Store,
        "department": data.Dept,
    }
